#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Audio Resource Code Generator
Generates audio_resource_map.h from CSV configuration
"""

import sys
import csv
import os
from datetime import datetime

def generate_header(csv_file, output_file, customer_name):
    """Generate audio resource map header from CSV"""
    
    resources = []
    
    # Read CSV file
    with open(csv_file, 'r', encoding='utf-8') as f:
        reader = csv.reader(f)
        for line in reader:
            # Skip empty lines and comments
            if not line or line[0].strip().startswith('#'):
                continue
            
            if len(line) >= 3:
                res_id = line[0].strip()
                vn_file = line[1].strip()
                en_file = line[2].strip()
                resources.append((res_id, vn_file, en_file))
    
    # Generate header file
    with open(output_file, 'w', encoding='utf-8') as f:
        f.write(f"""/**
 * @file audio_resource_map.h
 * @brief Audio Resource Map - Auto-generated from CSV
 * @note DO NOT EDIT THIS FILE MANUALLY
 * @customer {customer_name}
 * @generated {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
 */

#ifndef __AUDIO_RESOURCE_MAP_H__
#define __AUDIO_RESOURCE_MAP_H__

#include "audio_resource_manager.h"

#ifdef __cplusplus
extern "C" {{
#endif

/**
 * @brief Audio resource map entry structure
 */
typedef struct {{
    audio_resource_id_t id;
    const char *filename[AUDIO_LANG_MAX];
}} audio_resource_map_entry_t;

/**
 * @brief Customer-specific audio resource mapping table
 * @note Generated from audio_resources.csv
 */
static const audio_resource_map_entry_t CUSTOMER_AUDIO_RESOURCE_MAP[] = {{
""")
        
        # Write resource entries
        for res_id, vn_file, en_file in resources:
            f.write(f'    {{{res_id}, {{"{vn_file}", "{en_file}"}}}},\n')
        
        f.write("""};

/**
 * @brief Total number of audio resources
 */
#define CUSTOMER_AUDIO_RESOURCE_COUNT \\
    (sizeof(CUSTOMER_AUDIO_RESOURCE_MAP) / sizeof(audio_resource_map_entry_t))

#ifdef __cplusplus
}
#endif

#endif /* __AUDIO_RESOURCE_MAP_H__ */
""")
    
    print(f"Generated {len(resources)} audio resource mappings")
    print(f"Output: {output_file}")
    return 0

def main():
    if len(sys.argv) != 4:
        print("Usage: gen_audio_resources.py <csv_file> <output_header> <customer_name>")
        print("Example: gen_audio_resources.py audio_resources.csv audio_resource_map.h template")
        return 1
    
    csv_file = sys.argv[1]
    output_file = sys.argv[2]
    customer_name = sys.argv[3]
    
    if not os.path.exists(csv_file):
        print(f"Error: CSV file not found: {csv_file}")
        return 1
    
    return generate_header(csv_file, output_file, customer_name)

if __name__ == '__main__':
    sys.exit(main())
