#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
版本号自动生成工具
根据客户名、产品型号和Git提交次数自动生成版本头文件
版本格式: 客户名_产品型号_V2.xxxx (xxxx为Git提交次数)
"""

import os
import sys
import subprocess
import argparse
from datetime import datetime
from pathlib import Path


def get_git_commit_count(repo_path="."):
    """
    获取Git仓库的提交次数
    
    Args:
        repo_path: Git仓库路径
        
    Returns:
        int: 提交次数，如果获取失败返回0
    """
    try:
        # 尝试获取当前分支的提交次数
        result = subprocess.run(
            ["git", "rev-list", "--count", "HEAD"],
            cwd=repo_path,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            universal_newlines=True,
            timeout=5
        )
        if result.returncode == 0:
            count = int(result.stdout.strip())
            print(f"Git commit count: {count}")
            return count
    except (subprocess.TimeoutExpired, subprocess.SubprocessError, ValueError) as e:
        print(f"Warning: Failed to get git commit count: {e}")
    except FileNotFoundError:
        print("Warning: git command not found")
    
    return 0


def get_git_commit_hash(repo_path=".", short=True):
    """
    获取Git提交哈希值
    
    Args:
        repo_path: Git仓库路径
        short: 是否返回短哈希(7位)
        
    Returns:
        str: 提交哈希值，如果获取失败返回"unknown"
    """
    try:
        cmd = ["git", "rev-parse"]
        if short:
            cmd.append("--short")
        cmd.append("HEAD")
        
        result = subprocess.run(
            cmd,
            cwd=repo_path,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            universal_newlines=True,
            timeout=5
        )
        if result.returncode == 0:
            return result.stdout.strip()
    except Exception as e:
        print(f"Warning: Failed to get git commit hash: {e}")
    
    return "unknown"


def get_git_branch(repo_path="."):
    """
    Get current Git branch name
    
    Args:
        repo_path: Git repository path
        
    Returns:
        str: Branch name, "unknown" if failed
    """
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=repo_path,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            universal_newlines=True,
            timeout=5
        )
        if result.returncode == 0:
            return result.stdout.strip()
    except Exception as e:
        print(f"Warning: Failed to get git branch: {e}")
    
    return "unknown"


def is_git_dirty(repo_path="."):
    """
    Check if Git working directory has uncommitted changes
    
    Args:
        repo_path: Git repository path
        
    Returns:
        bool: True if dirty (has changes), False if clean
    """
    try:
        # Check for staged and unstaged changes
        result = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=repo_path,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            universal_newlines=True,
            timeout=5
        )
        if result.returncode == 0:
            # If output is not empty, repository is dirty
            return len(result.stdout.strip()) > 0
    except Exception as e:
        print(f"Warning: Failed to check git status: {e}")
    
    return False


def generate_version_header(customer_name, product_model, output_file, repo_path="."):
    """
    Generate version header file
    
    Args:
        customer_name: Customer name
        product_model: Product model
        output_file: Output file path
        repo_path: Git repository path
    """
    # Get Git information
    commit_count = get_git_commit_count(repo_path)
    commit_hash = get_git_commit_hash(repo_path, short=True)
    branch = get_git_branch(repo_path)
    is_dirty = is_git_dirty(repo_path)
    
    # Generate version number: CustomerName_ProductModel_V2.xxxx
    version_number = f"V2.{commit_count:04d}"
    full_version = f"{customer_name}_{product_model}_{version_number}"
    
    # Add dirty suffix if repository has uncommitted changes
    if is_dirty:
        full_version += "-dirty"
    
    # Get current time
    build_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    build_date = datetime.now().strftime("%Y%m%d")
    
    # Generate header file content
    header_content = f"""/**
 * @file app_version.h
 * @brief Auto-generated version information
 * @warning DO NOT EDIT THIS FILE MANUALLY!
 * 
 * Generated by: gen_version.py
 * Generated at: {build_time}
 */

#ifndef __APP_VERSION_H__
#define __APP_VERSION_H__

#ifdef __cplusplus
extern "C" {{
#endif

/* ========================================================================
 * Version Information
 * ======================================================================== */

/** Customer name */
#define APP_CUSTOMER_NAME       "{customer_name}"

/** Product model */
#define APP_PRODUCT_MODEL       "{product_model}"

/** Version number (V2.xxxx format) */
#define APP_VERSION_NUMBER      "{version_number}"

/** Full version string: CustomerName_ProductModel_V2.xxxx[-dirty] */
#define APP_VERSION_STRING      "{full_version}"

/** Major version (always 2) */
#define APP_VERSION_MAJOR       2

/** Minor version (git commit count) */
#define APP_VERSION_MINOR       {commit_count}

/* ========================================================================
 * Build Information
 * ======================================================================== */

/** Build date (YYYYMMDD format) */
#define APP_BUILD_DATE          "{build_date}"

/** Build time (YYYY-MM-DD HH:MM:SS format) */
#define APP_BUILD_TIME          "{build_time}"

/** Git commit hash (short) */
#define APP_GIT_COMMIT_HASH     "{commit_hash}"

/** Git branch */
#define APP_GIT_BRANCH          "{branch}"

/** Git commit count */
#define APP_GIT_COMMIT_COUNT    {commit_count}

/** Git dirty flag (1 = has uncommitted changes, 0 = clean) */
#define APP_GIT_DIRTY           {1 if is_dirty else 0}

/* ========================================================================
 * Helper Macros
 * ======================================================================== */

/** Get version string */
#define APP_GET_VERSION()       APP_VERSION_STRING

/** Get full build info string */
#define APP_GET_BUILD_INFO()    APP_VERSION_STRING " (" APP_GIT_COMMIT_HASH " @ " APP_BUILD_DATE ")"

/** Check if repository has uncommitted changes */
#define APP_IS_GIT_DIRTY()      (APP_GIT_DIRTY == 1)

#ifdef __cplusplus
}}
#endif

#endif /* __APP_VERSION_H__ */
"""
    
    # Ensure output directory exists
    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write to file
    with open(output_file, 'w', encoding='utf-8') as f:
        f.write(header_content)
    
    print(f"\n{'='*60}")
    print(f"Version header generated successfully!")
    print(f"{'='*60}")
    print(f"Customer:      {customer_name}")
    print(f"Product:       {product_model}")
    print(f"Version:       {version_number} (commit count: {commit_count})")
    print(f"Full version:  {full_version}")
    print(f"Git commit:    {commit_hash}")
    print(f"Git branch:    {branch}")
    print(f"Git dirty:     {'YES (uncommitted changes)' if is_dirty else 'NO (clean)'}")
    print(f"Build time:    {build_time}")
    print(f"Output file:   {output_file}")
    print(f"{'='*60}\n")


def load_product_config(customer_name, sdk_root):
    """
    Load product model from customer config file
    
    Args:
        customer_name: Customer name
        sdk_root: SDK root directory
        
    Returns:
        str: Product model, default value if not found
    """
    config_file = Path(sdk_root) / "customers" / customer_name / "product.ini"
    
    if config_file.exists():
        try:
            with open(config_file, 'r', encoding='utf-8') as f:
                for line in f:
                    line = line.strip()
                    if line.startswith("PRODUCT_MODEL="):
                        return line.split("=", 1)[1].strip()
        except Exception as e:
            print(f"Warning: Failed to read product config: {e}")
    
    # Return default product model
    return "SoundBox"


def main():
    parser = argparse.ArgumentParser(
        description="Auto-generate version header file",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python gen_version.py template SB100
  python gen_version.py template --auto-product
  python gen_version.py template -p SB100
  python gen_version.py -c template -p SB100
  python gen_version.py template PX200 -o output/app_version.h
        """
    )
    
    parser.add_argument(
        "customer",
        nargs="?",
        help="Customer name (e.g., template,...). Can be omitted if using -c/--customer-name"
    )
    
    parser.add_argument(
        "product",
        nargs="?",
        help="Product model (e.g., SB100, PX200). If omitted, use --auto-product or load from product.ini"
    )
    
    parser.add_argument(
        "-o", "--output",
        default="framework/common/app_version.h",
        help="Output header file path (default: framework/common/app_version.h)"
    )
    
    parser.add_argument(
        "--auto-product",
        action="store_true",
        help="Auto-load product model from customer's product.ini (default if product not specified)"
    )
    
    parser.add_argument(
        "-p", "--product-model",
        dest="product_model_override",
        help="Override product model (takes precedence over positional argument and auto-product)"
    )
    
    parser.add_argument(
        "-c", "--customer-name",
        dest="customer_name_override",
        help="Override customer name (takes precedence over positional argument)"
    )
    
    parser.add_argument(
        "--sdk-root",
        default=".",
        help="SDK root directory (default: current directory)"
    )
    
    args = parser.parse_args()
    
    # Determine customer name (priority: -c/--customer-name > positional argument)
    customer_name = args.customer_name_override if args.customer_name_override else args.customer
    
    if not customer_name:
        parser.error("Customer name is required (provide as positional argument or use -c/--customer-name)")
    
    # Determine product model (priority: -p/--product-model > positional > auto-load from config)
    product_model = None
    if args.product_model_override:
        product_model = args.product_model_override
        print(f"Using product model from argument: {product_model}")
    elif args.product:
        product_model = args.product
        print(f"Using product model from argument: {product_model}")
    else:
        # Auto-load from product.ini
        product_model = load_product_config(customer_name, args.sdk_root)
        print(f"Auto-detected product model: {product_model}")
    
    # Generate version header file
    generate_version_header(
        customer_name=customer_name,
        product_model=product_model,
        output_file=args.output,
        repo_path=args.sdk_root
    )
    
    return 0


if __name__ == "__main__":
    sys.exit(main())
