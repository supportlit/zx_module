#!/usr/bin/env python3
"""
Audio Resource Map Generator

This script generates a C header file from a CSV configuration file.
The generated header contains audio resource mappings with single filename per resource.
Language switching is done by selecting different audio file folders (e.g., res_VN/, res_EN/).

CSV Format: RESOURCE_ID,filename,description
- RESOURCE_ID: Audio resource identifier (e.g., AUDIO_RES_SYS_STARTUP)
- filename: Audio file name (e.g., sys_startup.mp3)
- description: Human-readable description

Similar to TTS_def.h design pattern.

Usage:
    python gen_audio_resources.py <csv_file> <output_header> <customer_name>

Example:
    python gen_audio_resources.py customers/template/audio_resources.csv \\
           customers/template/audio_resource_map.h template
"""

import csv
import sys
import os

def generate_header(csv_file, output_file, customer_name):
    """Generate C header file from CSV configuration"""
    
    if not os.path.exists(csv_file):
        print(f"Error: CSV file '{csv_file}' not found")
        return False
    
    resources = []
    
    # Read CSV file
    try:
        with open(csv_file, 'r', encoding='utf-8') as f:
            reader = csv.reader(f)
            line_num = 0
            for line in reader:
                line_num += 1
                
                # Skip empty lines and comments
                if not line or len(line) == 0:
                    continue
                if line[0].strip().startswith('#'):
                    continue
                
                # Skip header row (first line with RESOURCE_ID,filename,description)
                if line_num == 1 and line[0].strip().upper() == 'RESOURCE_ID':
                    continue
                
                # Parse: RESOURCE_ID,filename,description
                if len(line) >= 3:
                    resource_id = line[0].strip()
                    filename = line[1].strip()
                    description = line[2].strip()
                    
                    if resource_id and filename:
                        resources.append({
                            'id': resource_id,
                            'filename': filename,
                            'description': description
                        })
    except Exception as e:
        print(f"Error reading CSV file: {e}")
        return False
    
    if not resources:
        print("Error: No valid resources found in CSV file")
        return False
    
    # Generate header file
    try:
        with open(output_file, 'w', encoding='utf-8') as f:
            # Header guard
            guard_name = f"CUSTOMER_{customer_name.upper()}_AUDIO_RESOURCE_MAP_H"
            
            # File header
            f.write(f"/* Auto-generated audio resource map for {customer_name} customer */\n")
            f.write(f"/* DO NOT EDIT THIS FILE MANUALLY */\n")
            f.write(f"/* Regenerate using: python tools/gen_audio_resources.py */\n\n")
            
            f.write(f"#ifndef {guard_name}\n")
            f.write(f"#define {guard_name}\n\n")
            
            # Don't include audio_resource_types.h as it doesn't exist
            # audio_resource_id_t is defined in audio_resource_manager.h
            # which will include this file
            
            # Structure definition comment
            f.write("/**\n")
            f.write(" * Audio resource map entry structure (single filename design)\n")
            f.write(" * Language switching is done via folder selection:\n")
            f.write(" *   - Vietnamese: res_VN/filename.mp3\n")
            f.write(" *   - English: res_EN/filename.mp3\n")
            f.write(" * \n")
            f.write(" * Similar to TTS_def.h pattern where language is selected\n")
            f.write(" * at runtime by changing the resource folder path.\n")
            f.write(" */\n")
            f.write("typedef struct {\n")
            f.write("    audio_resource_id_t id;\n")
            f.write("    const char *filename;\n")
            f.write("} audio_resource_map_entry_t;\n\n")
            
            # Resource array
            f.write("/* Customer-specific audio resource mapping table */\n")
            f.write("static const audio_resource_map_entry_t CUSTOMER_AUDIO_RESOURCE_MAP[] = {\n")
            
            for res in resources:
                # Add comment with description
                if res['description']:
                    f.write(f"    /* {res['description']} */\n")
                f.write(f"    {{{res['id']}, \"{res['filename']}\"}},\n")
            
            f.write("};\n\n")
            
            # Resource count macro
            f.write(f"/* Total number of audio resources */\n")
            f.write(f"#define CUSTOMER_AUDIO_RESOURCE_COUNT {len(resources)}\n\n")
            
            # Close header guard
            f.write(f"#endif /* {guard_name} */\n")
    
    except Exception as e:
        print(f"Error writing header file: {e}")
        return False
    
    print(f"Generated {len(resources)} audio resource mappings for customer '{customer_name}'")
    print(f"Output: {output_file}")
    return True

def main():
    if len(sys.argv) != 4:
        print("Usage: python gen_audio_resources.py <csv_file> <output_header> <customer_name>")
        print("\nExample:")
        print("  python gen_audio_resources.py customers/template/audio_resources.csv \\")
        print("         customers/template/audio_resource_map.h template")
        sys.exit(1)
    
    csv_file = sys.argv[1]
    output_file = sys.argv[2]
    customer_name = sys.argv[3]
    
    if generate_header(csv_file, output_file, customer_name):
        sys.exit(0)
    else:
        sys.exit(1)

if __name__ == "__main__":
    main()
